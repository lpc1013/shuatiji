EVID_FALLBACK = [
    (re.compile(r'(?:故选|故答|因此选|所以选|答案选|应选|本题选|答案应为|正确答案应为|正确答案应){1}\s*[：:]?\s*([A-E])(?![A-Za-z0-9])'), 'concl'),
    (re.compile(r'(?:正确答案|本题答案|答案)\s*[是为]\s*[：:]?\s*([A-E])(?![A-Za-z0-9\u4e00-\u9fa5])'), 'concl'),
    (re.compile(r'(存在矛盾|并不严谨|不严谨|值得商榷|存在争议|有争议|本题无正确答案|无正确答案|请以教材为准|题目指定|本题指定|原.{0,10}参考答案|但原答案|正确答案应为|答案应为)'), 'mark'),
]


def find_evidence(text, kw):
    if kw:
        i = text.find(kw)
        if i >= 0:
            s = max(0, i - 110)
            return re.sub(r'\s+', ' ', text[s:i + 180]).strip()
    for rx, _ in EVID_FALLBACK:
        m = rx.search(text)
        if m:
            s = max(0, m.start() - 110)
            return re.sub(r'\s+', ' ', text[s:m.end() + 150]).strip()
    return re.sub(r'\s+', ' ', text[:260]).strip()


